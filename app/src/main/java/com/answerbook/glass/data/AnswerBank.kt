    val size: Int get() = answers.size

    /** 抽取一页；尽量避开刚刚出现的那一页。 */
    fun draw(excludingPage: Int? = null): Page {
        if (answers.isEmpty()) return Page("答案，正在路上。", 1)
        var index = Random.nextInt(answers.size)
        if (answers.size > 1 && excludingPage != null) {
            val previous = (excludingPage - 1).coerceIn(0, answers.size - 1)
            while (index == previous) {
                index = Random.nextInt(answers.size)
            }
        }
        return Page(answers[index], index + 1)
    }

    fun pageLabel(number: Int): String = number.toString().padStart(3, '0')
